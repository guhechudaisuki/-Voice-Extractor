"""Package only runtime code and media tools, then pin the EXE download hash."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import zipfile


ROOT = Path(__file__).resolve().parents[1]
URL = 'https://github.com/guhechudaisuki/-Voice-Extractor/releases/download/v3.0/VoiceExtractor_resources.zip'


def build(gpt_root: Path, destination: Path) -> str:
    entries = {}

    def tree(source, target, excluded=()):
        if not source.is_dir():
            raise FileNotFoundError(source)
        for file in sorted(source.rglob('*')):
            relative = file.relative_to(source)
            if (file.is_file() and not any(part in {'__pycache__', '.git', *excluded} for part in relative.parts)
                    and file.suffix.lower() not in {'.pyc', '.pth', '.pt', '.bin', '.ckpt', '.onnx', '.safetensors'}):
                entries[(Path(target) / relative).as_posix()] = file

    for name in ('extractor', 'launcher', 'vendor'):
        tree(ROOT / name, name, {'bin', 'obj'})
    tree(gpt_root / 'tools/uvr5', 'dependencies/uvr5', {'uvr5_weights'})
    tree(gpt_root / 'GPT_SoVITS/eres2net', 'dependencies/eres2net')
    for name in ('ffmpeg.exe', 'ffprobe.exe'):
        entries[f'tools/{name}'] = gpt_root / 'runtime' / name
    for name in ('desktop_worker.py', 'extract_cli.py', 'app.py', 'README.md', 'LICENSE', 'requirements-extra.txt'):
        entries[name] = ROOT / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as package:
        for name, file in sorted(entries.items()):
            if name == 'launcher/release_manifest.py':
                package.writestr(name, f'RESOURCE_URL = {URL!r}\nRESOURCE_SHA256 = ""\n')
            else:
                package.write(file, name)
    digest = hashlib.sha256(destination.read_bytes()).hexdigest()
    (ROOT / 'launcher/release_manifest.py').write_text(
        '"""Generated by scripts/package_resources.py before building the EXE."""\n'
        f'RESOURCE_URL = {URL!r}\nRESOURCE_SHA256 = {digest!r}\n', encoding='utf-8')
    return digest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--gpt-root', type=Path, default=ROOT.parent / 'GPT-SoVITS-v2pro-20250604')
    parser.add_argument('--output', type=Path, default=ROOT / 'dist/VoiceExtractor_resources.zip')
    args = parser.parse_args()
    digest = build(args.gpt_root.resolve(), args.output.resolve())
    print(f'{args.output}: {args.output.stat().st_size} bytes; SHA256 {digest}')
